/** Cadre du symbole seul (un peu de marge autour des formes). */
const MARK_BOX = { x: -8, y: 96, w: 882, h: 748 };

export function LogoMark({
  size = 32,
  tone = "color",
  className = "",
}: {
  size?: number;
  tone?: Tone;
  className?: string;
}) {
  const id = useId().replace(/[^a-zA-Z0-9_-]/g, "");
  return (
    <svg
      height={size}
      width={Math.round((size * MARK_BOX.w) / MARK_BOX.h)}
      viewBox={`${MARK_BOX.x} ${MARK_BOX.y} ${MARK_BOX.w} ${MARK_BOX.h}`}
      aria-hidden="true"
      focusable="false"
      className={className}
    >
      <MarkPaths tone={tone} id={`m${id}`} />
    </svg>
  );
}

/** Symbole + nom ; `size` est la hauteur du logo en pixels. */
export function Logo({
  tone = "color",
  size = 40,
  className = "",
}: {
  tone?: Tone;
  size?: number;
  className?: string;
}) {
  const id = useId().replace(/[^a-zA-Z0-9_-]/g, "");
  const text =
    tone === "inverse" ? "text-cream" : tone === "color" ? "text-forest dark:text-foreground" : "";
  return (
    <svg
      role="img"
      aria-label="Aux Petits Oignons"
      viewBox="0 0 2831.29 958.43"
      height={size}
      width={Math.round((size * 2831.29) / 958.43)}
      className={`${text} ${className}`}
    >
      <MarkPaths tone={tone} id={`l${id}`} />
      <g fill="currentColor">
        {WORDMARK.map((l, i) => (
          <path
            key={i}
            d={l.d}
            className={l.initial && tone !== "mono" ? INITIAL_CLASS[l.initial] : undefined}
          />
        ))}
      </g>
    </svg>
  );
}
